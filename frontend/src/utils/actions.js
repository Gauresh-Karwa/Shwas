/**
 * actions.js: pure helpers for the Ward Actions page (no React, no network).
 * Kept free of Vite-only imports so node test suites can run them.
 */

// Page routing (hash based, so a reload or a shared link keeps the page)
export function viewFromHash(hash) {
    return /^#\/actions\/?$/.test(hash ?? '') ? 'actions' : 'map';
}

export function hashForView(view) {
    return view === 'actions' ? '#/actions' : '#/';
}

// Labels shown to people (the backend sends short machine ids)
export const SIGNALS = {
    waste_burning: 'Open burning',
    forecast_crossing: 'Rising pollution',
    stagnation: 'Stagnant air',
    traffic: 'Traffic peak',
    dust: 'Road and construction dust',
    inflow: 'Smoke arriving from upwind',
};

// Baseline card signal keys (generated by the engine, not real live detectors)
export const BASELINE_SIGNALS = new Set([
    'dust_suppression',
    'traffic_corridor',
    'swm_vigilance',
    'met_inversion_advisory',
]);

export const SEVERITY = {
    high: { label: 'High priority', rank: 3 },
    medium: { label: 'Medium priority', rank: 2 },
    low: { label: 'For information', rank: 1 },
};

export const CONFIDENCE_HINT = {
    high: 'Several strong signs agree.',
    likely: 'The signs point this way, with some uncertainty.',
    possible: 'Worth checking; the signs are weaker or the station is far.',
    indicative: 'An early hint only.',
};

export function signalLabel(id) {
    return SIGNALS[id] ?? String(id ?? '').replace(/_/g, ' ');
}

export function severityInfo(severity) {
    return SEVERITY[severity] ?? { label: String(severity ?? ''), rank: 0 };
}

// Numbers formatting
export function formatPopulation(n) {
    if (n == null || Number.isNaN(Number(n))) return '-';
    return Number(n).toLocaleString('en-IN');
}

export function formatKm(km) {
    if (km == null) return null;
    return `${Number(km).toFixed(1)} km`;
}

export function trendInfo(trend) {
    if (trend === 'rising') return { arrow: '+', text: 'rising' };
    if (trend === 'falling') return { arrow: '-', text: 'falling' };
    return { arrow: '=', text: 'steady' };
}

// Cards filtering and categorization
export const actionCards = ward => (ward?.cards ?? []).filter(c => !c.advisory && !c.baseline);
export const advisoryCards = ward => (ward?.cards ?? []).filter(c => c.advisory);
export const baselineCards = ward => (ward?.cards ?? []).filter(c => c.baseline);
export const needsAction = ward => actionCards(ward).length > 0;

/** Highest severity among a ward's live action cards; advisory-only wards count as "low"; none = null. */
export function wardTopSeverity(ward) {
    const acts = actionCards(ward);
    if (acts.length) {
        return acts.reduce((best, c) => (severityInfo(c.severity).rank > severityInfo(best).rank ? c.severity : best), acts[0].severity);
    }
    return advisoryCards(ward).filter(c => !c.baseline).length ? 'low' : null;
}

/** Wards come from the backend already ranked; keep that order and apply the filters. */
export function filterWards(wards, { signal = 'all', onlyActions = false } = {}) {
    return (wards ?? []).filter(w => {
        if (onlyActions && !needsAction(w)) return false;
        if (signal !== 'all' && !actionCards(w).some(c => c.signal === signal)) return false;
        return true;
    });
}

/** Live signals that appear on at least one non-baseline card, for the filter chips. */
export function signalsInUse(wards) {
    const seen = new Set();
    for (const w of wards ?? [])
        for (const c of (w.cards ?? []))
            if (!c.baseline) seen.add(c.signal);
    return Object.keys(SIGNALS).filter(id => seen.has(id)).concat([...seen].filter(id => !(id in SIGNALS) && !BASELINE_SIGNALS.has(id)));
}

export function summarise(data) {
    const wards = data?.wards ?? [];
    return {
        total: data?.total_wards_evaluated ?? wards.length,
        needAction: wards.filter(needsAction).length,
        high: wards.filter(w => wardTopSeverity(w) === 'high').length,
        estimated: wards.filter(w => w.is_estimated).length,
        rules: data?.rules?.active ?? null,
    };
}

/** The ward to show first: the top-ranked ward that needs action, else the first ward. */
export function defaultWardId(wards) {
    const first = (wards ?? []).find(needsAction) ?? (wards ?? [])[0];
    return first?.ward_id ?? null;
}

export function rankOf(wards, wardId) {
    const ranked = (wards ?? []).filter(needsAction);
    const i = ranked.findIndex(w => w.ward_id === wardId);
    return i >= 0 ? i + 1 : null;
}
